DROP TABLE IF EXISTS partner_products CASCADE;
DROP TABLE IF EXISTS products CASCADE;
DROP TABLE IF EXISTS partners CASCADE;
DROP TABLE IF EXISTS product_type CASCADE;
DROP TABLE IF EXISTS material_type CASCADE;

CREATE TABLE product_type (
    id SERIAL PRIMARY KEY,
    name VARCHAR(150) NOT NULL UNIQUE,
    coefficient NUMERIC(6,2) NOT NULL CHECK (coefficient > 0)
);

CREATE TABLE material_type (
    id SERIAL PRIMARY KEY,
    name VARCHAR(150) NOT NULL UNIQUE,
    defect_percent NUMERIC(7,4) NOT NULL CHECK (defect_percent >= 0 AND defect_percent < 1)
);

CREATE TABLE products (
    id SERIAL PRIMARY KEY,
    product_type_id INTEGER NOT NULL REFERENCES product_type(id) ON UPDATE CASCADE ON DELETE RESTRICT,
    material_type_id INTEGER NOT NULL REFERENCES material_type(id) ON UPDATE CASCADE ON DELETE RESTRICT,
    name VARCHAR(255) NOT NULL,
    article VARCHAR(20) NOT NULL UNIQUE,
    min_price NUMERIC(12,2) NOT NULL CHECK (min_price >= 0)
);

CREATE TABLE partners (
    id SERIAL PRIMARY KEY,
    partner_type VARCHAR(10) NOT NULL,
    name VARCHAR(200) NOT NULL,
    director VARCHAR(150) NOT NULL,
    email VARCHAR(150) NOT NULL,
    phone VARCHAR(30) NOT NULL,
    legal_address VARCHAR(300) NOT NULL,
    inn VARCHAR(12) NOT NULL UNIQUE,
    rating INTEGER NOT NULL CHECK (rating >= 0)
);

CREATE TABLE partner_products (
    id SERIAL PRIMARY KEY,
    product_id INTEGER NOT NULL REFERENCES products(id) ON UPDATE CASCADE ON DELETE RESTRICT,
    partner_id INTEGER NOT NULL REFERENCES partners(id) ON UPDATE CASCADE ON DELETE CASCADE,
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    sale_date DATE NOT NULL
);

